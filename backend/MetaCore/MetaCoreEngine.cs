    /// <summary>
    /// Classifies a single metadata key-value entry and assigns its priority and action.
    /// </summary>
    public ClassifiedMetadetail ClassifyTag(string key, JsonNode? value, MetaSanitizeOptions? options = null)
    {
        options ??= new MetaSanitizeOptions();
        var (groupPrefix, normalizedKey) = SplitGroupPrefix(key);

        var (priority, category, reason, isEmbeddedWritable, isRuntimeSynthetic) =
            ResolveBaseClassification(key, groupPrefix, normalizedKey, options.StrictMode);

        // Apply user-provided overrides if specified
        var forceKeep = options.KeepTags.Any(t =>
            t.Equals(key, StringComparison.OrdinalIgnoreCase) ||
            t.Equals(normalizedKey, StringComparison.OrdinalIgnoreCase));
        var forceRemove = options.RemoveTags.Any(t =>
            t.Equals(key, StringComparison.OrdinalIgnoreCase) ||
            t.Equals(normalizedKey, StringComparison.OrdinalIgnoreCase));

        MetaAction action;
        if (forceRemove)
        {
            action = MetaAction.Remove;
            if (priority < MetaPriority.High)
            {
                priority = MetaPriority.High;
                reason = "Explicitly marked for removal by sanitization policy";
            }
        }
        else if (forceKeep)
        {
            action = MetaAction.Keep;
            reason = "Explicitly preserved by sanitization policy";
        }
        else
        {
            action = priority switch
            {
                MetaPriority.Required => options.KeepRequired ? MetaAction.Keep : MetaAction.Remove,
                MetaPriority.Low => options.KeepLowPriority ? MetaAction.Keep : MetaAction.Remove,
                _ => MetaAction.Remove
            };
        }

        return new ClassifiedMetadetail
        {
            Key = key,
            NormalizedKey = normalizedKey,
            Value = value?.DeepClone(),
            Priority = priority,
            PriorityScore = ScoreForPriority(priority),
            Category = category,
            Action = action,
            IsSensitive = priority is MetaPriority.High or MetaPriority.Critical,
            IsRequired = priority == MetaPriority.Required,
            IsEmbeddedWritable = isEmbeddedWritable,
            IsRuntimeSynthetic = isRuntimeSynthetic,
            Reason = reason
        };
    }

    /// <summary>
    /// Evaluates an entire metadata dictionary, assigns priorities to every metadetail,
    /// and returns an ordered MetaCore report + writable preservation list.
    /// </summary>
    public MetaCoreReport AnalyzeMetadata(JsonObject metadata, MetaSanitizeOptions? options = null)
    {
        options ??= new MetaSanitizeOptions();
        var details = new List<ClassifiedMetadetail>();

        foreach (var kvp in metadata)
        {
            details.Add(ClassifyTag(kvp.Key, kvp.Value, options));
        }

        // Order so the highest sensitivity / priority items surface first, followed by Low and Required.
        details = details
            .OrderByDescending(d => d.PriorityScore)
            .ThenBy(d => d.Category, StringComparer.OrdinalIgnoreCase)
            .ThenBy(d => d.Key, StringComparer.OrdinalIgnoreCase)
            .ToList();

        var requiredCount = details.Count(d => d.Priority == MetaPriority.Required);
        var lowCount = details.Count(d => d.Priority == MetaPriority.Low);
        var highCount = details.Count(d => d.Priority == MetaPriority.High);
        var criticalCount = details.Count(d => d.Priority == MetaPriority.Critical);
        var sensitiveCount = highCount + criticalCount;

        var kept = details.Where(d => d.Action == MetaAction.Keep).ToList();
        var removed = details.Where(d => d.Action == MetaAction.Remove).ToList();

        var writablePreserveTags = kept
            .Where(d => d.IsEmbeddedWritable && !d.IsRuntimeSynthetic)
            .Select(d => d.NormalizedKey)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        var riskLevel = criticalCount > 0
            ? "Critical"
            : highCount > 0
                ? "High"
                : details.Count > 0
                    ? "Low"
                    : "Clean";

        return new MetaCoreReport
        {
            TotalCount = details.Count,
            RequiredCount = requiredCount,
            LowPriorityCount = lowCount,
            HighPriorityCount = highCount,
            CriticalPriorityCount = criticalCount,
            SensitiveCount = sensitiveCount,
            KeptCount = kept.Count,
            RemovedCount = removed.Count,
            RiskLevel = riskLevel,
            Details = details,
            KeptTags = kept.Select(d => d.Key).ToList(),
            RemovedTags = removed.Select(d => d.Key).ToList(),
            WritablePreserveTags = writablePreserveTags
        };
    }

    private static (string GroupPrefix, string NormalizedKey) SplitGroupPrefix(string key)
    {
        var colonIdx = key.IndexOf(':');
        if (colonIdx > 0 && colonIdx < key.Length - 1)
        {
            return (key[..colonIdx], key[(colonIdx + 1)..]);
        }
        return (string.Empty, key);
    }

    private static (MetaPriority Priority, string Category, string Reason, bool IsEmbeddedWritable, bool IsRuntimeSynthetic)
        ResolveBaseClassification(string rawKey, string groupPrefix, string normalizedKey, bool strictMode)
    {
        var isRuntime = RuntimeSyntheticKeys.Contains(rawKey) || RuntimeSyntheticKeys.Contains(normalizedKey);

        if (ExactRules.TryGetValue(rawKey, out var exactRaw))
        {
            return (exactRaw.Priority, exactRaw.Category, exactRaw.Reason, exactRaw.IsEmbeddedWritable, exactRaw.IsRuntimeSynthetic);
        }

        if (ExactRules.TryGetValue(normalizedKey, out var exactNorm))
        {
            return (exactNorm.Priority, exactNorm.Category, exactNorm.Reason, exactNorm.IsEmbeddedWritable, exactNorm.IsRuntimeSynthetic);
        }

        if (NonWritableStructuralKeys.Contains(normalizedKey))
        {
            return (MetaPriority.Required, "File Structure", "Required structural or decoding attribute", false, isRuntime);
        }

        if (WritableRequiredKeys.Contains(normalizedKey))
        {
            return (MetaPriority.Required, "Structural & Color Rendering", "Required for accurate rendering, orientation, or color profile", true, isRuntime);
        }

        if (LowPriorityKeys.Contains(normalizedKey))
        {
            return (MetaPriority.Low, "Camera & Technical Settings", "Low-priority benign technical parameter", true, isRuntime);
        }

        // Group-level sensitive checks (e.g. XMP-dc:*, IPTC:*, GPS:*, MakerNotes:*)
        if (!string.IsNullOrEmpty(groupPrefix))
        {
            if (groupPrefix.StartsWith("GPS", StringComparison.OrdinalIgnoreCase))
                return (MetaPriority.Critical, "Location & GPS", "GPS group tag exposes location data", true, isRuntime);
            if (groupPrefix.StartsWith("MakerNote", StringComparison.OrdinalIgnoreCase))
                return (MetaPriority.High, "Vendor / MakerNotes", "Vendor MakerNotes often embed serial numbers and internal state", true, isRuntime);
        }

        // Pattern-based sensitivity detection
        if (CriticalPattern.IsMatch(normalizedKey))
        {
            return (MetaPriority.Critical, "Sensitive Metadata", "Matches critical PII, location, identifier, or path pattern", !isRuntime, isRuntime);
        }

        if (HighPattern.IsMatch(normalizedKey))
        {
            return (MetaPriority.High, "Sensitive Metadata", "Matches timestamp, device fingerprint, software, or descriptive metadata pattern", !isRuntime, isRuntime);
        }

        // Unclassified tags inside XMP/IPTC/Photoshop/SVG editor blocks are treated conservatively as High sensitivity.
        if (groupPrefix.StartsWith("XMP", StringComparison.OrdinalIgnoreCase) ||
            groupPrefix.StartsWith("IPTC", StringComparison.OrdinalIgnoreCase) ||
            groupPrefix.StartsWith("Photoshop", StringComparison.OrdinalIgnoreCase) ||
            groupPrefix.StartsWith("inkscape", StringComparison.OrdinalIgnoreCase) ||
            groupPrefix.StartsWith("sodipodi", StringComparison.OrdinalIgnoreCase))
        {
            return (MetaPriority.High, "Extended Metadata", "Extended or editor metadata tag removed for privacy", true, isRuntime);
        }

        if (strictMode && !isRuntime)
        {
            return (MetaPriority.High, "Unclassified Metadata", "Removed under strict sanitization mode", true, false);
        }

        return (MetaPriority.Low, "Technical Metadata", "Low-priority unclassified technical field", !isRuntime, isRuntime);
    }

    private static int ScoreForPriority(MetaPriority priority) => priority switch
    {
        MetaPriority.Critical => 100,
        MetaPriority.High => 75,
        MetaPriority.Low => 25,
        MetaPriority.Required => 0,
        _ => 25
    };
